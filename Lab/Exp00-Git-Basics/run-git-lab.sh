#!/usr/bin/env bash
# Exp 0 (Part A + optional Part B) — Git hands-on, run end to end in a throwaway sandbox.
#
# Every command the manuals ask for is executed for real and its output is appended to
# git-lab-transcript.md. Nothing outside the sandbox is touched:
#   * HOME is pointed at the sandbox, so `git config --global ...` writes the sandbox's
#     ~/.gitconfig and `~/.ssh/id_ed25519` is a brand-new throwaway key — the machine's real
#     git identity, config and SSH keys are left exactly as they were.
#   * "GitHub" is played by bare repositories under $WORK/home/github/*.git, and a second
#     clone pushing to them plays "editing the file on the GitHub website".
#
# Usage (Git Bash):  bash run-git-lab.sh            # rebuilds the sandbox from scratch

set -u
HERE="$(cd "$(dirname "$0")" && pwd)"
OUT="$HERE/git-lab-transcript.md"
REALHOME="$HOME"
WORK="${TMPDIR:-/tmp}/exp00-git-lab"

rm -rf "$WORK"
mkdir -p "$WORK/home"
export HOME="$WORK/home"
export GIT_EDITOR=true            # accept git's default message where the manual opens an editor
export GIT_MERGE_AUTOEDIT=no
export GIT_SSH_COMMAND="ssh -o BatchMode=yes -o StrictHostKeyChecking=accept-new"
export LANG=C.UTF-8
cd "$HOME"

INBLK=0
startblk(){ [ $INBLK -eq 0 ] && { printf '```console\n' >>"$OUT"; INBLK=1; }; }
endblk(){ [ $INBLK -eq 1 ] && { printf '```\n\n' >>"$OUT"; INBLK=0; }; }
sec(){ endblk; printf '## %s\n\n' "$1" >>"$OUT"; }
sub(){ endblk; printf '### %s\n\n' "$1" >>"$OUT"; }
p(){ endblk; printf '%s\n\n' "$*" >>"$OUT"; }
run(){
  startblk
  printf '$ %s\n' "$1" >>"$OUT"
  eval "$1" >>"$OUT" 2>&1
  local rc=$?
  [ $rc -ne 0 ] && printf '[exit code %d]\n' "$rc" >>"$OUT"
  return 0
}

cat >"$OUT" <<EOF
# Exp 0 — Git hands-on transcript

Generated by \`run-git-lab.sh\` on $(date '+%Y-%m-%d %H:%M %Z') — every block below is the
literal command that was run and the literal output it produced (stdout and stderr), in order.
A non-zero exit status is shown as \`[exit code N]\`. Sandbox: \`$WORK\` (HOME was pointed
there for the whole run).

EOF

