run 'git config --global commit.gpgsign true'
p "To let git *verify* the signatures locally (GitHub does this server-side once the key is added as a **signing** key), an allowed-signers file maps the email to the key:"
run 'echo "suryansh.mishra.sm6@gmail.com namespaces=\"git\" $(cat ~/.ssh/id_ed25519.pub)" > ~/.ssh/allowed_signers'
run 'git config --global gpg.ssh.allowedSignersFile ~/.ssh/allowed_signers'
run 'git config --global --list'

sec "A5. Test the SSH connection (Part A §5)"
p "With the brand-new sandbox key — it has not been added to any GitHub account, so GitHub must refuse it. This is exactly the manual's *\"Error: permission denied (SSH)\"* case:"
run 'ssh -o BatchMode=yes -o StrictHostKeyChecking=accept-new -T git@github.com'
p "The student's own machine pushes to GitHub over **HTTPS with a token held by a credential helper** (Part B 002, method 1), not SSH — the existing \`~/.ssh/id_ed25519\` on this machine is not registered on the GitHub account either, so it is refused the same way:"
run "ssh -o BatchMode=yes -o IdentitiesOnly=yes -o StrictHostKeyChecking=accept-new -i '$REALHOME/.ssh/id_ed25519' -T git@github.com"
p "The working authentication path on this machine (real HOME, read-only checks; the token is masked by gh itself):"
run "HOME='$REALHOME' git config --global --get-all credential.https://github.com.helper"
run "HOME='$REALHOME' gh auth status 2>&1 | head -6"
run "HOME='$REALHOME' git ls-remote https://github.com/smirk-dev/Backend-Development.git HEAD"
p "Registering the key is a GitHub account change (Settings → SSH and GPG keys → *New SSH key*, then again as *New SSH signing key*), done by the student in the browser; once added, \`ssh -T git@github.com\` answers *\"Hi smirk-dev! You've successfully authenticated\"*."

